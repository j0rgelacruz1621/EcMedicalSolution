CREATE INDEX IF NOT EXISTS "idx_reports_doctor_status" ON "reports" ("doctor_id", "status");
CREATE INDEX IF NOT EXISTS "idx_tasks_doctor_status" ON "tasks" ("doctor_id", "status");

-- ============================================================================
-- Foreign keys
-- ============================================================================
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_offices_medical_center') THEN
        ALTER TABLE "offices" ADD CONSTRAINT "fk_offices_medical_center" FOREIGN KEY ("medical_center_id") REFERENCES "medical_centers"("id") ON DELETE SET NULL;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'appointments_doctor_id_fkey') THEN
        ALTER TABLE "appointments" ADD CONSTRAINT "appointments_doctor_id_fkey" FOREIGN KEY ("doctor_id") REFERENCES "doctors"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'appointments_medical_center_id_fkey') THEN
        ALTER TABLE "appointments" ADD CONSTRAINT "appointments_medical_center_id_fkey" FOREIGN KEY ("medical_center_id") REFERENCES "medical_centers"("id") ON DELETE SET NULL ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'appointments_office_id_fkey') THEN
        ALTER TABLE "appointments" ADD CONSTRAINT "appointments_office_id_fkey" FOREIGN KEY ("office_id") REFERENCES "offices"("id") ON DELETE SET NULL ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_appointments_patient') THEN
        ALTER TABLE "appointments" ADD CONSTRAINT "fk_appointments_patient" FOREIGN KEY ("patient_id") REFERENCES "patients"("id") ON DELETE SET NULL;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'patient_vitals_patient_id_fkey') THEN
        ALTER TABLE "patient_vitals" ADD CONSTRAINT "patient_vitals_patient_id_fkey" FOREIGN KEY ("patient_id") REFERENCES "patients"("id") ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_vitals_appointment') THEN
        ALTER TABLE "patient_vitals" ADD CONSTRAINT "fk_vitals_appointment" FOREIGN KEY ("appointment_id") REFERENCES "appointments"("id") ON DELETE SET NULL;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'reports_patient_id_fkey') THEN
        ALTER TABLE "reports" ADD CONSTRAINT "reports_patient_id_fkey" FOREIGN KEY ("patient_id") REFERENCES "patients"("id") ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'reports_doctor_id_fkey') THEN
        ALTER TABLE "reports" ADD CONSTRAINT "reports_doctor_id_fkey" FOREIGN KEY ("doctor_id") REFERENCES "doctors"("id") ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'reports_appointment_id_fkey') THEN
        ALTER TABLE "reports" ADD CONSTRAINT "reports_appointment_id_fkey" FOREIGN KEY ("appointment_id") REFERENCES "appointments"("id") ON DELETE SET NULL;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tasks_doctor_id_fkey') THEN
        ALTER TABLE "tasks" ADD CONSTRAINT "tasks_doctor_id_fkey" FOREIGN KEY ("doctor_id") REFERENCES "doctors"("id") ON DELETE CASCADE;
    END IF;
END $$;

-- ============================================================================
-- Triggers updated_at
-- ============================================================================
DROP TRIGGER IF EXISTS trigger_update_medical_centers ON "medical_centers";
CREATE TRIGGER trigger_update_medical_centers BEFORE UPDATE ON "medical_centers"
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trigger_update_patients ON "patients";
CREATE TRIGGER trigger_update_patients BEFORE UPDATE ON "patients"
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trigger_update_appointments ON "appointments";
CREATE TRIGGER trigger_update_appointments BEFORE UPDATE ON "appointments"
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trigger_update_reports ON "reports";
CREATE TRIGGER trigger_update_reports BEFORE UPDATE ON "reports"
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trigger_update_tasks ON "tasks";
CREATE TRIGGER trigger_update_tasks BEFORE UPDATE ON "tasks"
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
