-- Baseline: tablas base faltantes en Supabase (extraído de supabase-schema.sql)
-- Idempotente. La BD ya tiene doctors y doctor_schedules; aquí se crean las demás.

-- ============================================================================
-- Enums
-- ============================================================================
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'appointment_status_enum') THEN
        CREATE TYPE "appointment_status_enum" AS ENUM ('SCHEDULED','CONFIRMED','IN_PROGRESS','COMPLETED','CANCELLED','NO_SHOW');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'appointment_type_enum') THEN
        CREATE TYPE "appointment_type_enum" AS ENUM ('FIRST_TIME','CONTROL','EMERGENCY','ROUTINE');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'day_of_week_enum') THEN
        CREATE TYPE "day_of_week_enum" AS ENUM ('Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'gender_enum') THEN
        CREATE TYPE "gender_enum" AS ENUM ('Male','Female','Other');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'report_status_enum') THEN
        CREATE TYPE "report_status_enum" AS ENUM ('DRAFT','PENDING_REVIEW','APPROVED','REJECTED');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'task_priority_enum') THEN
        CREATE TYPE "task_priority_enum" AS ENUM ('LOW','MEDIUM','HIGH','URGENT');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'task_status_enum') THEN
        CREATE TYPE "task_status_enum" AS ENUM ('PENDING','IN_PROGRESS','COMPLETED','CANCELLED');
    END IF;
END $$;

-- Trigger genérico updated_at
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- ============================================================================
-- Tablas (en orden de dependencias)
-- ============================================================================
CREATE TABLE IF NOT EXISTS "medical_centers" (
    "id" BIGSERIAL NOT NULL,
    "name" VARCHAR(150) NOT NULL,
    "address" TEXT,
    "phone" VARCHAR(20),
    "is_active" BOOLEAN DEFAULT true,
    "created_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "medical_centers_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "offices" (
    "id" BIGSERIAL NOT NULL,
    "medical_center_id" BIGINT,
    "office_number" VARCHAR(50) NOT NULL,
    "location_details" VARCHAR(255),
    "is_active" BOOLEAN DEFAULT true,
    "created_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "offices_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "users" (
    "id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "created_at" TIMESTAMPTZ DEFAULT now() NOT NULL,
    "user_name" VARCHAR NOT NULL,
    "password" VARCHAR NOT NULL,
    "rol" VARCHAR,
    "application" VARCHAR,
    CONSTRAINT "users_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "patients" (
    "id" BIGSERIAL NOT NULL,
    "national_id" VARCHAR(30) NOT NULL,
    "first_name" VARCHAR(100) NOT NULL,
    "last_name" VARCHAR(100) NOT NULL,
    "email" VARCHAR(150) NOT NULL,
    "phone" VARCHAR(20) NOT NULL,
    "age" INTEGER NOT NULL,
    "origin" VARCHAR(100),
    "address" VARCHAR(255),
    "gender" "gender_enum" NOT NULL,
    "medical_history_notes" TEXT,
    "is_active" BOOLEAN DEFAULT true,
    "created_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "patients_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "appointments" (
    "id" BIGSERIAL NOT NULL,
    "appointment_code" VARCHAR(20) NOT NULL,
    "patient_id" BIGINT,
    "doctor_id" BIGINT NOT NULL,
    "medical_center_id" BIGINT,
    "office_id" BIGINT,
    "appointment_date" DATE NOT NULL,
    "start_time" TIME NOT NULL,
    "end_time" TIME NOT NULL,
    "reason_for_visit" TEXT,
    "status" "appointment_status_enum" DEFAULT 'SCHEDULED'::"appointment_status_enum",
    "created_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "appointments_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "patient_vitals" (
    "id" BIGSERIAL NOT NULL,
    "patient_id" BIGINT NOT NULL,
    "appointment_id" BIGINT,
    "blood_pressure_systolic" INTEGER,
    "blood_pressure_diastolic" INTEGER,
    "heart_rate_bpm" INTEGER,
    "weight_kg" NUMERIC(5,2),
    "measured_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    "created_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "patient_vitals_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "reports" (
    "id" BIGSERIAL NOT NULL,
    "patient_id" BIGINT NOT NULL,
    "doctor_id" BIGINT NOT NULL,
    "appointment_id" BIGINT,
    "title" VARCHAR(200) NOT NULL,
    "content" TEXT,
    "file_url" VARCHAR(500),
    "status" "report_status_enum" DEFAULT 'PENDING_REVIEW'::"report_status_enum",
    "created_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "reports_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "tasks" (
    "id" BIGSERIAL NOT NULL,
    "doctor_id" BIGINT NOT NULL,
    "title" VARCHAR(200) NOT NULL,
    "description" TEXT,
    "priority" "task_priority_enum" DEFAULT 'MEDIUM'::"task_priority_enum",
    "status" "task_status_enum" DEFAULT 'PENDING'::"task_status_enum",
    "due_date" TIMESTAMPTZ,
    "created_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "tasks_pkey" PRIMARY KEY ("id")
);

-- ============================================================================
-- Constraints únicos
-- ============================================================================
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'appointments_appointment_code_key') THEN
        ALTER TABLE "appointments" ADD CONSTRAINT "appointments_appointment_code_key" UNIQUE ("appointment_code");
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'patients_national_id_key') THEN
        ALTER TABLE "patients" ADD CONSTRAINT "patients_national_id_key" UNIQUE ("national_id");
    END IF;
END $$;

